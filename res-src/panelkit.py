"""Building blocks for panel artwork: fonts as outlines, colour themes, the Panel class and the shared knob and
button graphics. Each module's panel lives in panels/<slug>.py and is built from these; panel.py writes them all.

Every panel carries a hidden "components" layer in the SDK helper.py convention (red params, green inputs, blue
outputs, magenta lights, yellow custom widgets), which the C++ side reads back at runtime to place each widget (see
PanelLayout in src/ui.hpp). Labels are converted to outlines, since Rack's SVG renderer ignores <text>.
"""
import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = json.loads((ROOT / 'plugin.json').read_text())


def num(v):
    return f'{v:.3f}'.rstrip('0').rstrip('.')


def mix(a, b, t):
    """Blend two #RRGGBB colours."""
    pa, pb = bytes.fromhex(a[1:]), bytes.fromhex(b[1:])
    return '#' + bytes(round(x + (y - x) * t) for x, y in zip(pa, pb)).hex().upper()


class Font:
    def __init__(self, path):
        tt = TTFont(path)
        self.glyphs, self.cmap = tt.getGlyphSet(), tt.getBestCmap()
        self.upem = tt['head'].unitsPerEm
        self.cap = tt['OS/2'].sCapHeight / self.upem

    def width(self, text, size):
        return sum(self.glyphs[self.cmap[ord(c)]].width for c in text) * size / self.upem

    def path(self, text, x, y, size, anchor='middle'):
        """Outlines of `text` as SVG path data, with its cap height centred on `y`."""
        x -= {'start': 0, 'middle': 0.5, 'end': 1}[anchor] * self.width(text, size)
        y += self.cap * size / 2
        s = size / self.upem
        pen = SVGPathPen(self.glyphs, num)
        for c in text:
            glyph = self.glyphs[self.cmap[ord(c)]]
            glyph.draw(TransformPen(pen, (s, 0, 0, -s, x, y)))
            x += glyph.width * s
        return pen.getCommands()


